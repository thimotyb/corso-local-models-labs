"""Analyze the stored results and write everything the course material needs.

    python analyze.py

Writes results/summary.json (all numbers), results/REPORT.md (the tables) and results/ERRORS.md
(the hand-written tickets each backend gets wrong). No model is called: it only reads results/*.json.
"""
from __future__ import annotations

import json
import statistics
from pathlib import Path

import cascade
from metrics import TEAMS, task_metrics, truth_index, vector
from run_bench import HERE, load_items

TASKS = ("team", "urgent", "refund")
THRESHOLD = 0.7
HAND_FROM = 100  # tickets with id >= 100 are the hand-written hard ones


def load_results() -> dict[str, list[dict]]:
    return {p.stem: json.loads(p.read_text())["rows"] for p in sorted((HERE / "results").glob("*.json")) if p.stem != "summary"}


def ok_ids(rows: list[dict]) -> set[int]:
    return {r["id"] for r in rows if not r["error"]}


def metrics_for(rows, ids, items) -> dict:
    return {t: task_metrics(t, [r for r in rows if r["id"] in ids], items, THRESHOLD) for t in TASKS}


def latency(rows) -> dict:
    v = [1000 * r["latency"] for r in rows if not r["error"]]
    return {"mean_ms": statistics.mean(v), "median_ms": statistics.median(v), "p95_ms": sorted(v)[int(0.95 * len(v))]} if v else {}


def by_kind(rows, items) -> dict:
    out = {}
    for t in TASKS:
        out[t] = {}
        for kind, keep in (("template", lambda i: i < HAND_FROM), ("hand_written", lambda i: i >= HAND_FROM)):
            sel = [r for r in rows if not r["error"] and keep(r["id"])]
            if sel:
                correct = sum(max(range(len(vector(t, r[t]))), key=vector(t, r[t]).__getitem__) == truth_index(t, items[r["id"]]) for r in sel)
                out[t][kind] = {"n": len(sel), "acc": correct / len(sel)}
    return out


def reliability(rows, items) -> list[dict]:
    """Pooled over the three questions: stated confidence against actual accuracy, per bin of 0.1."""
    bins: dict[int, list] = {}
    for r in rows:
        if r["error"]:
            continue
        for t in TASKS:
            p = vector(t, r[t])
            top = max(range(len(p)), key=p.__getitem__)
            bins.setdefault(min(9, int(p[top] * 10)), []).append((p[top], top == truth_index(t, items[r["id"]])))
    return [{"lo": b / 10, "hi": (b + 1) / 10, "n": len(v), "conf": sum(c for c, _ in v) / len(v), "acc": sum(k for _, k in v) / len(v)}
            for b, v in sorted(bins.items())]


def wrong_hand_written(rows, items) -> list[dict]:
    out = []
    for r in rows:
        if r["error"] or r["id"] < HAND_FROM:
            continue
        for t in TASKS:
            p = vector(t, r[t])
            top = max(range(len(p)), key=p.__getitem__)
            if top != truth_index(t, items[r["id"]]):
                shown = (TEAMS[top] if t == "team" else bool(top))
                out.append({"id": r["id"], "task": t, "truth": items[r["id"]][t], "predicted": shown, "confidence": p[top], "text": items[r["id"]]["text"]})
    return out


def main() -> None:
    items = {i["id"]: i for i in load_items()}
    res = load_results()
    common = set.intersection(*[ok_ids(r) for r in res.values()])
    two = {k: res[k] for k in ("opendecider-nano", "xgboost-tfidf") if k in res}
    full = set.intersection(*[ok_ids(r) for r in two.values()])
    tiers = {"nano alone": [two["opendecider-nano"]], "nano then XGBoost": [two["opendecider-nano"], two["xgboost-tfidf"]], "XGBoost alone": [two["xgboost-tfidf"]]}
    summary = {
        "threshold": THRESHOLD,
        "common": {"n": len(common), "ids": sorted(common), "metrics": {k: metrics_for(r, common, items) for k, r in res.items()}},
        "full": {"n": len(full), "metrics": {k: metrics_for(r, full, items) for k, r in two.items()}},
        "latency": {k: latency(r) for k, r in res.items()},
        "by_kind": {k: by_kind(r, items) for k, r in two.items()},
        "reliability_nano": reliability(two["opendecider-nano"], items),
        "cascade": [{"setup": name, "threshold": t, **cascade.replay(rows, items, t)} for t in (0.5, 0.6, 0.7, 0.8, 0.9) for name, rows in tiers.items()],
        "wrong_hand_written": {k: wrong_hand_written(r, items) for k, r in two.items()},
    }
    out = HERE / "results"
    (out / "summary.json").write_text(json.dumps(summary, indent=1, default=float))

    md = [f"# Judge benchmark: stored results\n\nConfidence threshold {THRESHOLD}. Generated by `analyze.py` from `results/*.json`; environment and provenance in `runs/environment.json`.\n"]
    for title, block in (("Tickets answered by every backend", summary["common"]), ("Full set, backends that ran on every ticket", summary["full"])):
        md.append(f"## {title} ({block['n']} tickets)\n")
        for t in TASKS:
            md.append(f"### {t}\n\n| backend | n | acc | ECE | Brier | conf | acc@c | cov@c |\n|---|---|---|---|---|---|---|---|")
            for k, m in block["metrics"].items():
                x = m[t]
                md.append(f"| {k} | {x['n']} | {x['acc']:.2f} | {x['ece']:.3f} | {x['brier']:.3f} | {x['conf']:.2f} | {x['acc_conf']:.2f} | {x['cov_conf']:.2f} |")
            md.append("")
    md.append("## Latency per ticket (three questions)\n\n| backend | mean | median | p95 |\n|---|---|---|---|")
    for k, v in summary["latency"].items():
        md.append(f"| {k} | {v['mean_ms']:.0f} ms | {v['median_ms']:.0f} ms | {v['p95_ms']:.0f} ms |")
    md.append("\n## Accuracy by kind of ticket (template-built vs hand-written)\n\n| backend | question | template (n) | hand-written (n) |\n|---|---|---|---|")
    for k, bk in summary["by_kind"].items():
        for t in TASKS:
            a, b = bk[t].get("template"), bk[t].get("hand_written")
            md.append(f"| {k} | {t} | {a['acc']:.2f} ({a['n']}) | {b['acc']:.2f} ({b['n']}) |")
    md.append("\n## Reliability of OpenDecider-nano (all three questions pooled)\n\n| stated confidence | answers | mean confidence | actual accuracy |\n|---|---|---|---|")
    for b in summary["reliability_nano"]:
        md.append(f"| {b['lo']:.1f} to {b['hi']:.1f} | {b['n']} | {b['conf']:.2f} | {b['acc']:.2f} |")
    md.append("\n## Cascade replay (120 tickets x 3 questions, no model calls)\n\n| setup | threshold | auto accuracy | sent to a person | passed to 2nd tier |\n|---|---|---|---|---|")
    for c in summary["cascade"]:
        md.append(f"| {c['setup']} | {c['threshold']} | {c['auto_acc']:.3f} | {100 * c['human_share']:.1f}% | {100 * c['escalated_share']:.1f}% |")
    (out / "REPORT.md").write_text("\n".join(md) + "\n")

    err = ["# Hand-written tickets answered wrongly\n\nTickets 100 to 119 are written to be hard. One row per wrong answer; the confidence is that of the wrong top answer.\n"]
    for k, wrong in summary["wrong_hand_written"].items():
        err.append(f"## {k} ({len(wrong)} wrong answers)\n\n| id | question | correct | answered | confidence | ticket |\n|---|---|---|---|---|---|")
        for w in wrong:
            err.append(f"| {w['id']} | {w['task']} | {w['truth']} | {w['predicted']} | {w['confidence']:.2f} | {w['text']} |")
        err.append("")
    (out / "ERRORS.md").write_text("\n".join(err))
    print("wrote results/summary.json, REPORT.md, ERRORS.md")


if __name__ == "__main__":
    main()
